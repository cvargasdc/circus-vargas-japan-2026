#!/usr/bin/env node
/**
 * Build companion.html — single self-contained file (CSS + data + app inlined).
 * Prefer this URL for phones when CDN serves .html as text/plain.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const css = fs.readFileSync(path.join(root, 'styles.css'), 'utf8');
const data = fs.readFileSync(path.join(root, 'data.js'), 'utf8');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');

/*
 * Pronunciation clips for the Say it tab: audio/manifest.json (made by
 * scripts/gen_phrase_audio.py) maps each phrase's Japanese text → mp3.
 * Only clips for phrases currently in data.js are embedded (base64 data URIs),
 * so companion.html stays one offline-capable file. Phrases without a clip
 * fall back to speechSynthesis (ja-JP) in app.js.
 */
function buildPhraseAudio() {
  const manifestPath = path.join(root, 'audio', 'manifest.json');
  let clips = {};
  try {
    clips = JSON.parse(fs.readFileSync(manifestPath, 'utf8')).clips || {};
  } catch (e) {
    console.warn('No audio/manifest.json — Say it tab will use speechSynthesis only');
  }
  let readings = {};
  try {
    readings = JSON.parse(fs.readFileSync(path.join(root, 'audio', 'readings.json'), 'utf8')).readings || {};
  } catch (e) { /* optional */ }

  const sandbox = { window: {} };
  require('vm').runInNewContext(data, sandbox);
  const cats = ((sandbox.window.TRIP_DATA || {}).phrases || {}).categories || [];
  const jaList = [...new Set(cats.flatMap((c) => (c.items || []).map((i) => (i.ja || '').trim())).filter(Boolean))];

  const out = { clips: {}, tts: {} };
  const missing = [];
  let bytes = 0;
  for (const ja of jaList) {
    const c = clips[ja];
    const file = c && path.join(root, 'audio', c.file);
    if (c && fs.existsSync(file)) {
      const buf = fs.readFileSync(file);
      bytes += buf.length;
      out.clips[ja] = 'data:audio/mpeg;base64,' + buf.toString('base64');
      if (c.tts) out.tts[ja] = c.tts;
    } else {
      missing.push(ja);
      if (readings[ja]) out.tts[ja] = readings[ja];
    }
  }
  console.log(`Phrase audio: ${Object.keys(out.clips).length}/${jaList.length} phrases embedded (${bytes} bytes mp3)`);
  if (missing.length) {
    console.log(`  ${missing.length} phrase(s) without audio (speech fallback): ${missing.join(' / ')}`);
    console.log('  → run: python3 scripts/gen_phrase_audio.py');
  }
  const js = `/* Auto-generated by scripts/build-companion.js from audio/ — do not edit */\n` +
    `window.PHRASE_AUDIO = ${JSON.stringify(out).replace(/<\//g, '<\\/')};\n`;
  return js;
}
const phraseAudio = buildPhraseAudio();
fs.writeFileSync(path.join(root, 'phrase-audio.js'), phraseAudio, 'utf8');

